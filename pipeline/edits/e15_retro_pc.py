"""Edit #15 (integration, Sakina approved 2026-11-01): retro IBM PC on the left-wall cabinet.

Applies exactly what components/retro_pc/place_preview.py previewed (and Sakina approved as preview):
widen the cabinet 0.30 m toward the viewer's left (-Y), replace the old PC / CRT2 / Term / keyboard objects with
components/retro_pc/export/retro_pc_source.blend, shift the cabinet 4 cm (-Y), stick her photo (Polaroid) upright on the
monitor's right end with a 3 mm white border and a tight crop. See components/retro_pc/INTEGRATION.md.
Bake group: Station (unchanged). The old fake screen glow light L5_IBM_Screen is hidden (the new screen is emissive).
"""
import bpy, math, os
from mathutils import Vector

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "components", "retro_pc", "export", "retro_pc_source.blend")
WIDEN, SHIFT_Y, CY = 0.30, -0.04, 1.25
PHOTO_X, PHOTO_Y, PHOTO_Z = -2.650, 1.394 - 0.04, 0.870


def _vshift(o, fn):
    o.data = o.data.copy()
    mw = o.matrix_world
    inv = mw.inverted()
    for v in o.data.vertices:
        w = mw @ v.co
        w.y += fn(w.y)
        v.co = inv @ w
    o.data.update()


def _widen(D, root, W):
    for o in list(D.objects):
        if o.type != "MESH" or o.parent != root or not o.name.startswith(("Cabinet_", "Drawer_")):
            continue
        n = o.name
        cy = sum((o.matrix_world @ Vector(c)).y for c in o.bound_box) / 8
        if n in ("Cabinet_Body", "Cabinet_Top", "Cabinet_Plinth", "Cabinet_Crown") or n.startswith(("Drawer_Front", "Drawer_Gap")) \
                or (n.startswith("Drawer_Mould") and n[-1] in "TB"):
            _vshift(o, lambda y: -W if y < CY else 0.0)
        elif n.startswith(("Cabinet_Foot", "Drawer_Mould")):
            _vshift(o, lambda y, d=(-W if cy < CY else 0.0): d)
        elif n.startswith(("Drawer_Bar", "Drawer_Escutcheon", "Drawer_Keyhole")):
            _vshift(o, lambda y: -W / 2)


def _ensure_screen_texture():
    """The monitor screen PNG is generated by build_retro_pc.make_images() and is gitignored (export/tex_src/), so the
    committed source .blend points at a file that does not exist on a fresh clone. Regenerate it and pack it."""
    import importlib.util, sys, pathlib
    tex = pathlib.Path(ROOT) / "components" / "retro_pc" / "export" / "tex_src"
    if not (tex / "pc_screen.png").exists():
        sys.path.insert(0, ROOT)
        sys.path.insert(0, os.path.join(ROOT, "components", "retro_pc"))
        spec = importlib.util.spec_from_file_location("build_retro_pc_mod", os.path.join(ROOT, "components", "retro_pc", "build_retro_pc.py"))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        mod.make_images(tex)
    assert (tex / "pc_screen.png").exists(), "pc_screen.png could not be generated"


def _pack_new_images(D):
    n = 0
    for img in D.images:
        fp = bpy.path.abspath(img.filepath) if img.filepath else ""
        if "retro_pc" in fp.replace("\\", "/") and not img.packed_file and os.path.exists(fp):
            img.reload()
            img.pack()
            n += 1
    return n


def apply():
    _ensure_screen_texture()
    D = bpy.data
    sc = bpy.context.scene
    root = D.objects["Station_Root"]
    station = D.collections["Station"]
    if D.objects.get("L5_IBM_Screen"):
        D.objects["L5_IBM_Screen"].hide_render = True
    bpy.context.view_layer.update()
    _widen(D, root, WIDEN)

    old = [o for o in list(D.objects)
           if (o.parent == root and o.name.startswith(("PC_", "CRT2_", "Term_")))
           or (o.name.startswith("KB_") and any(c.name == "Station" for c in o.users_collection))]
    assert old, "no old PC objects found to replace (scene changed?)"
    for o in old:
        D.objects.remove(o, do_unlink=True)

    with D.libraries.load(SRC) as (src, dst):
        dst.objects = list(src.objects)
    holder = D.objects.new("NewPC_Root", None)
    station.objects.link(holder)
    holder.location = (-2.675, 1.25, 0.55)
    holder.rotation_euler = (0, 0, math.radians(90))
    new = [o for o in dst.objects if o is not None]
    for o in new:
        station.objects.link(o)
        o.parent = holder
    bpy.context.view_layer.update()
    holder.parent = root
    holder.matrix_parent_inverse = root.matrix_world.inverted()
    root.location.y += SHIFT_Y

    pol = D.objects.get("Polaroid")
    if pol:
        bpy.context.view_layer.update()
        m = pol.matrix_world.copy()
        m.translation = Vector((PHOTO_X, PHOTO_Y, PHOTO_Z))
        pol.matrix_world = m
        bd = D.objects.get("Polaroid_Border")
        if bd:
            bd.data = bd.data.copy()
            for v in bd.data.vertices:
                v.co.x = 0.040 if v.co.x > 0 else -0.040
                v.co.z = 0.051 if v.co.z > 0 else -0.035
        ph = D.objects["Polaroid_Photo"]
        me = ph.data.copy()
        ph.data = me
        for v in me.vertices:
            v.co.x = 0.037 if v.co.x > 0 else -0.037
            v.co.z = 0.040 if v.co.z > 0 else -0.040
        for l in me.uv_layers.active.data:
            l.uv = (0.88 if l.uv[0] > 0.5 else 0.14, 0.80 if l.uv[1] > 0.5 else 0.0)
        pol.rotation_euler = (0, 0, 0)
    packed = _pack_new_images(D)
    bpy.context.view_layer.update()
    print(f"e15: packed {packed} retro PC image(s); removed {len(old)} old PC objects, added {len(new)} retro PC objects, cabinet widened {WIDEN} m, shifted {SHIFT_Y} m", flush=True)
